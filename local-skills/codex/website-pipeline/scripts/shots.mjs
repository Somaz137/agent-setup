#!/usr/bin/env node
/**
 * shots.mjs — G10 (cross-browser) and the capture half of G11 (visual regression).
 *
 * Captures every route × width × browser in one process. That is the part which
 * would otherwise be 20-60 separate browser tool calls; doing it here is the
 * single biggest token saving in the pipeline.
 *
 *   node scripts/shots.mjs http://localhost:3000
 *   node scripts/shots.mjs https://example.netlify.app --browsers chromium,webkit
 *   node scripts/shots.mjs http://localhost:3000 --routes /,/pricing --widths 390,1440
 *   node scripts/shots.mjs http://localhost:3000 --scaffold   # write visual.spec.ts and exit
 *
 * Routes are read from /sitemap.xml unless --routes is given.
 *
 * DIFFING IS NOT DONE HERE ON PURPOSE. Playwright's own toHaveScreenshot is the
 * right tool for regression and already handles thresholds, masking and diff
 * images. `--scaffold` writes a spec that uses it. This script owns capture:
 * review shots, handoff artifacts, and the per-variant record G18 asks for.
 *
 * Requires: npm i -D playwright && npx playwright install
 */

import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const args = process.argv.slice(2);
const flag = (n, d = null) => {
  const i = args.indexOf(`--${n}`);
  return i !== -1 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : d;
};
const base = args.find((a) => /^https?:\/\//.test(a));

const WIDTHS = (flag('widths', '390,768,1440')).split(',').map(Number);
const BROWSERS = (flag('browsers', 'chromium,firefox,webkit')).split(',');
const OUT = flag('out', 'docs/snapshots');
const FULL = args.includes('--full-page');

// ---------------------------------------------------------------------------
// --scaffold: hand regression to Playwright's own comparator
// ---------------------------------------------------------------------------

const SPEC = `import { test, expect } from '@playwright/test';

// Visual regression. Generated by scripts/shots.mjs --scaffold.
//
// Baselines live in Git and are reviewed in the PR, per G11. Regenerate with:
//   npx playwright test visual.spec.ts --update-snapshots
//
// BASELINES ARE SINGLE-MACHINE BY DECISION (2026-09-03).
// Font rendering differs between Windows, macOS and Linux, so the same unchanged
// page differs by thousands of pixels across operating systems. Generate AND
// compare on the one Windows dev box. Do not run these in a Linux CI container:
// every test would fail with nothing actually broken, and a check that cries
// wolf gets ignored, which costs more than having no check.
// Revisit only if someone else joins the work or builds move to the cloud.

// WHY settle() EXISTS (2026-09-04): the first scaffold failed 11 of 15 with
// "Failed to take two consecutive stable screenshots". A fullPage capture
// scrolls the document to stitch the image, which progressively triggers
// lazy-loaded images, so no two consecutive captures matched. Waiting for the
// load event was not enough either: img.complete is true before an image is
// DECODED, and an undecoded image paints during the stitch. Flipping every
// image to eager and awaiting decode() is what makes the comparison
// deterministic. Do not remove this to "simplify" the spec.
async function settle(page) {
  await page.evaluate(() => {
    for (const img of Array.from(document.images)) img.loading = 'eager';
  });
  await page.evaluate(async () => {
    await Promise.all(
      Array.from(document.images).map((i) =>
        i.decode ? i.decode().catch(() => undefined) : Promise.resolve(),
      ),
    );
    if (document.fonts?.ready) await document.fonts.ready;
  });
  // One extra frame so the compositor has painted what decode() prepared.
  await page.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))));
}

const ROUTES = ${JSON.stringify(['/'], null, 0)}; // extend as routes are added
const WIDTHS = ${JSON.stringify(WIDTHS)};

for (const route of ROUTES) {
  for (const width of WIDTHS) {
    test(\`\${route} @ \${width}\`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(route, { waitUntil: 'domcontentloaded' });
      // NOT networkidle: a dev server holds an HMR websocket open for the
      // life of the page, so the network is never idle and this can only end
      // by timing out — silently, blaming a timeout rather than the cause.
      // The settle step below is both stricter and deterministic.
      await settle(page);
      await expect(page).toHaveScreenshot(\`\${route.replace(/\\//g, '_') || 'home'}-\${width}.png\`, {
        fullPage: true,
        animations: 'disabled',        // stop CSS animations mid-flight
        caret: 'hide',
        // Mask anything that legitimately changes between runs.
        mask: [page.locator('[data-testid="live"], time, .marquee')],
        maxDiffPixelRatio: 0.01,       // tune per component, not globally
      });
    });
  }
}
`;

if (args.includes('--scaffold')) {
  const target = flag('spec', 'tests/visual.spec.ts');
  mkdirSync(join(process.cwd(), target, '..'), { recursive: true });
  if (existsSync(join(process.cwd(), target))) {
    console.error(`refusing to overwrite existing ${target}`);
    process.exit(1);
  }
  writeFileSync(join(process.cwd(), target), SPEC);
  console.log(`wrote ${target}`);
  console.log('run: npx playwright test --update-snapshots   (creates baselines)');
  process.exit(0);
}

if (!base) {
  console.error('usage: node scripts/shots.mjs <base-url> [--routes /,/a] [--widths 390,1440]');
  console.error('       node scripts/shots.mjs --scaffold          # write a Playwright regression spec');
  process.exit(2);
}

// ---------------------------------------------------------------------------
// Capture
// ---------------------------------------------------------------------------

let playwright;
try {
  playwright = await import('playwright');
} catch {
  console.error('playwright is not installed in this project.');
  console.error('  npm i -D playwright && npx playwright install');
  process.exit(2);
}

const origin = new URL(base).origin;

async function discoverRoutes() {
  const given = flag('routes');
  if (given) return given.split(',');
  try {
    const res = await fetch(`${origin}/sitemap.xml`);
    if (!res.ok) throw new Error(String(res.status));
    const xml = await res.text();
    const locs = [...xml.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)].map((m) => {
      try { return new URL(m[1]).pathname; } catch { return m[1]; }
    });
    if (locs.length) return locs;
  } catch { /* fall through */ }
  console.warn('no sitemap.xml — falling back to "/". Pass --routes to widen.');
  return ['/'];
}

const routes = await discoverRoutes();
mkdirSync(join(process.cwd(), OUT), { recursive: true });

const slug = (r) => (r === '/' ? 'home' : r.replace(/^\/|\/$/g, '').replace(/\//g, '-'));
let taken = 0;
const failures = [];

console.log(`\nshots — ${origin}`);
console.log(`${routes.length} route(s) × ${WIDTHS.length} width(s) × ${BROWSERS.length} browser(s) ` +
            `= ${routes.length * WIDTHS.length * BROWSERS.length} shot(s)\n`);

for (const browserName of BROWSERS) {
  let browser;
  try {
    browser = await playwright[browserName].launch();
  } catch (err) {
    failures.push(`${browserName}: launch failed — ${err.message.split('\n')[0]}`);
    continue;
  }

  for (const width of WIDTHS) {
    const context = await browser.newContext({
      viewport: { width, height: 900 },
      deviceScaleFactor: 1,
      reducedMotion: 'reduce',
    });
    const page = await context.newPage();

    for (const route of routes) {
      const url = `${origin}${route.startsWith('/') ? route : `/${route}`}`;
      const file = join(OUT, `${browserName}-${slug(route)}-${width}.png`);
      try {
        // domcontentloaded, never networkidle — see the note in the scaffold above.
        const res = await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 30_000 });
        if (res && !res.ok()) failures.push(`${browserName} ${route} @${width} → HTTP ${res.status()}`);
        // Freeze animations so repeat runs are comparable.
        await page.addStyleTag({
          content: `*,*::before,*::after{animation:none!important;transition:none!important}`,
        });
        await page.screenshot({ path: file, fullPage: FULL, animations: 'disabled' });
        taken++;
        process.stdout.write('.');
      } catch (err) {
        failures.push(`${browserName} ${route} @${width} → ${err.message.split('\n')[0]}`);
        process.stdout.write('x');
      }
    }
    await context.close();
  }
  await browser.close();
}

console.log(`\n\n${taken} shot(s) → ${OUT}`);
if (failures.length) {
  console.log(`\n${failures.length} failure(s):`);
  for (const f of failures) console.log(`  · ${f}`);
}
console.log('\nFor regression rather than review, use: node scripts/shots.mjs --scaffold\n');

process.exit(failures.length ? 1 : 0);
